#!/usr/bin/env python3
"""Generate runtime/src/menu/practice_settings.hpp from practice_settings.json.
Edit the JSON (labels, options, descriptions) and run this script; the header is
included by the recomp menu runtime."""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent
data = json.loads((root / "practice_settings.json").read_text())
out = []
out.append('// Generated by menu/generate_header.py from practice_settings.json.')
out.append('// Edit the JSON (labels/options/descriptions) or this header directly.')
out.append('#pragma once')
out.append('#include "recomp_menu.hpp"')
out.append('namespace ps2::menu {')
out.append('inline constexpr const char *kMenuTitle = %s;' % json.dumps(data.get("title", "RECOMP SETTINGS"), ensure_ascii=False))
out.append('inline constexpr const char *kMenuSubtitle = %s;' % json.dumps(data.get("subtitle", ""), ensure_ascii=False))
out.append('inline constexpr const char *kMenuFooter = %s;' % json.dumps(data.get("footer", ""), ensure_ascii=False))
out.append('inline std::vector<Section> practice_settings_sections() {')
out.append('    return {')
for sec in data["sections"]:
    out.append('        Section{%s, %s, {' % (json.dumps(sec["id"], ensure_ascii=False), json.dumps(sec["title"], ensure_ascii=False)))
    for it in sec["items"]:
        opts = it["options"]
        if it["value"] not in opts:
            opts = [it["value"]] + opts
        val = opts.index(it["value"])
        out.append('            Item{%s, %s, {%s}, %d, %s},' % (
            json.dumps(it["id"], ensure_ascii=False),
            json.dumps(it["label"], ensure_ascii=False),
            ", ".join(json.dumps(o, ensure_ascii=False) for o in opts),
            val,
            json.dumps(it.get("description", ""), ensure_ascii=False)))
    out.append('        }},')
out.append('    };')
out.append('}')
out.append('} // namespace ps2::menu')
(root.parent / "runtime/src/menu/practice_settings.hpp").write_text("\n".join(out) + "\n")
print("wrote runtime/src/menu/practice_settings.hpp")
