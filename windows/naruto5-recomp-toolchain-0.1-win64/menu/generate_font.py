#!/usr/bin/env python3
"""Generate runtime/src/menu/menu_font.hpp.

The menu uses a 12x20 monospace bitmap font (DejaVu Sans Mono 17px) with ASCII
32..126 plus the Latin-1 supplement (160..255), so Portuguese accents such as
OPÇÕES / NÃO SALVO work. Run this after changing the font size/typeface.
"""
import pathlib
import re
import subprocess
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "runtime/src/menu/menu_font.hpp"
W, H = 12, 20
FONT = "DejaVu-Sans-Mono"
POINT = 17


def glyph_rows(codepoint: int) -> list[int]:
    with tempfile.NamedTemporaryFile("w", encoding="utf-8", suffix=".txt", delete=False) as f:
        f.write(chr(codepoint))
        path = f.name
    try:
        out = subprocess.run(
            ["magick", "-background", "black", "-fill", "white", "-font", FONT,
             "-pointsize", str(POINT), "label:@" + path, "-gravity", "northwest",
             "-extent", f"{W}x{H}", "-threshold", "50%", "-compress", "none", "pbm:-"],
            stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, check=False,
        ).stdout
    finally:
        pathlib.Path(path).unlink(missing_ok=True)
    lines = out.split(b"\n")
    bits: list[int] = []
    for line in lines[2:]:
        for token in line.split():
            if token in (b"0", b"1"):
                bits.append(int(token))
    if len(bits) < W * H:
        bits += [0] * (W * H - len(bits))
    bits = bits[: W * H]
    rows = []
    for y in range(H):
        value = 0
        for x in range(W):
            # ImageMagick PBM: 0 is the white glyph, 1 is the black background.
            if bits[y * W + x] == 0:
                value |= 1 << x
        rows.append(value)
    return rows


def emit_array(name: str, codepoints: range) -> list[str]:
    rows: list[int] = []
    for cp in codepoints:
        rows.extend(glyph_rows(cp))
    lines = [f"inline constexpr std::uint16_t {name}[{len(rows)}] = {{"]
    for i in range(0, len(rows), 10):
        lines.append("    " + ", ".join("0x%03X" % v for v in rows[i:i + 10]) + ",")
    lines.append("};")
    return lines


def main() -> None:
    lines = [
        "// Generated by menu/generate_font.py (DejaVuSansMono 17px, 12x20 cells).",
        "#pragma once",
        "#include <cstdint>",
        "namespace ps2::menu {",
        f"inline constexpr int kFontW = {W}, kFontH = {H}, kFontFirst = 32, kFontCount = 95;",
        "inline constexpr int kFontLatinFirst = 160, kFontLatinCount = 96;",
    ]
    lines += emit_array("kFont", range(32, 127))
    lines += emit_array("kFontLatin", range(160, 256))
    lines += ["} // namespace ps2::menu", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
